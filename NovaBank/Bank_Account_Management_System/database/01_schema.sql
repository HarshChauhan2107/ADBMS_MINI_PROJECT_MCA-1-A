-- NovaBank | Oracle schema
-- Target: Oracle Database 19c or later (XE/Free editions are suitable for a lab project).
-- Run while connected as the BANKAPP schema owner in the correct PDB.

SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

CREATE SEQUENCE seq_bank_account_no START WITH 100000001 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE seq_bank_txn_ref START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE bank_customers (
    customer_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    full_name     VARCHAR2(100) NOT NULL,
    email         VARCHAR2(120),
    phone         VARCHAR2(20),
    address       VARCHAR2(250),
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_bank_customers PRIMARY KEY (customer_id),
    CONSTRAINT ck_customer_name CHECK (LENGTH(TRIM(full_name)) >= 2)
);

CREATE TABLE bank_accounts (
    account_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    account_no    VARCHAR2(20) NOT NULL,
    customer_id   NUMBER NOT NULL,
    account_type  VARCHAR2(12) NOT NULL,
    balance       NUMBER(14,2) DEFAULT 0 NOT NULL,
    status        VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    opened_on     DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_bank_accounts PRIMARY KEY (account_id),
    CONSTRAINT uq_bank_account_no UNIQUE (account_no),
    CONSTRAINT fk_account_customer FOREIGN KEY (customer_id)
        REFERENCES bank_customers(customer_id),
    CONSTRAINT ck_account_type CHECK (account_type IN ('SAVINGS','CURRENT')),
    CONSTRAINT ck_account_balance CHECK (balance >= 0),
    CONSTRAINT ck_account_status CHECK (status IN ('ACTIVE','FROZEN','CLOSED'))
);

CREATE TABLE bank_transactions (
    txn_id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    txn_ref              VARCHAR2(24) NOT NULL,
    account_id           NUMBER NOT NULL,
    txn_type             VARCHAR2(15) NOT NULL,
    amount               NUMBER(14,2) NOT NULL,
    balance_after        NUMBER(14,2) NOT NULL,
    description          VARCHAR2(250),
    related_account_no   VARCHAR2(20),
    created_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_bank_transactions PRIMARY KEY (txn_id),
    CONSTRAINT uq_bank_txn_ref UNIQUE (txn_ref),
    CONSTRAINT fk_txn_account FOREIGN KEY (account_id)
        REFERENCES bank_accounts(account_id),
    CONSTRAINT ck_txn_type CHECK (txn_type IN
        ('OPENING','DEPOSIT','WITHDRAWAL','TRANSFER_IN','TRANSFER_OUT')),
    CONSTRAINT ck_txn_amount CHECK (amount > 0),
    CONSTRAINT ck_txn_balance CHECK (balance_after >= 0)
);

CREATE TABLE bank_audit_log (
    audit_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    account_id     NUMBER NOT NULL,
    old_status     VARCHAR2(10),
    new_status     VARCHAR2(10),
    changed_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    changed_by     VARCHAR2(128) DEFAULT USER NOT NULL,
    CONSTRAINT pk_bank_audit_log PRIMARY KEY (audit_id),
    CONSTRAINT fk_audit_account FOREIGN KEY (account_id)
        REFERENCES bank_accounts(account_id)
);

CREATE INDEX ix_accounts_customer ON bank_accounts(customer_id);
CREATE INDEX ix_transactions_account_date ON bank_transactions(account_id, created_at DESC);
CREATE INDEX ix_transactions_date ON bank_transactions(created_at DESC);

CREATE OR REPLACE TRIGGER trg_bank_accounts_bu
BEFORE UPDATE ON bank_accounts
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
    IF NVL(:OLD.status, '~') <> NVL(:NEW.status, '~') THEN
        INSERT INTO bank_audit_log (account_id, old_status, new_status, changed_by)
        VALUES (:OLD.account_id, :OLD.status, :NEW.status, SYS_CONTEXT('USERENV','SESSION_USER'));
    END IF;
END;
/

-- The transaction table is an append-only ledger. Corrections should be posted as
-- compensating entries through a separately controlled business process.
CREATE OR REPLACE TRIGGER trg_bank_txn_immutable
BEFORE UPDATE OR DELETE ON bank_transactions
BEGIN
    RAISE_APPLICATION_ERROR(-20070, 'Transaction history is immutable. Post a correcting transaction instead.');
END;
/

